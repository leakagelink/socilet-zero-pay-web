/**
 * Auto-generate `public/sitemap-blog.xml` from `src/data/blogData.ts`.
 *
 * Why: keeping the sitemap in sync with new blog posts manually is error-prone
 * and was already drifting (some posts missing, some lastmod dates stale).
 *
 * How it works:
 *   1. Reads `src/data/blogData.ts` as text and extracts every entry's
 *      `slug` and `dateISO` / `date` using regex (no need to spin up ts-node).
 *   2. Emits a fresh sitemap with stable formatting:
 *        - /blog index entry first (priority 0.8, changefreq daily)
 *        - one <url> per post, sorted newest-first by date
 *        - <lastmod> uses dateISO when present, else parses `date`
 *        - <priority> 0.9 for posts published in the current/last year, else 0.8
 *   3. Writes the file and prints a short summary.
 *
 * Runs automatically as part of `npm run build` (via package.json).
 * Also exports `getBlogSlugs()` so `scripts/prerender.mjs` can reuse the
 * same source of truth instead of hardcoding the slug list.
 */

import { readFile, writeFile } from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const BLOG_DATA = path.join(ROOT, 'src', 'data', 'blogData.ts');
const OUT_FILE = path.join(ROOT, 'public', 'sitemap-blog.xml');
const SITE_URL = 'https://socilet.in';

// ---------------------------------------------------------------------------
// Parse blogData.ts
// ---------------------------------------------------------------------------
export async function getBlogPosts() {
  const src = await readFile(BLOG_DATA, 'utf8');

  // Match each object literal in the blogPosts array. We're conservative:
  // each entry must have at least slug + (date or dateISO).
  const entries = [];
  const objectRegex = /\{[^{}]*?slug:\s*["']([^"']+)["'][^{}]*?\}/g;
  let m;
  while ((m = objectRegex.exec(src)) !== null) {
    const block = m[0];
    const slug = m[1];
    const dateISO = (block.match(/dateISO:\s*["']([^"']+)["']/) || [])[1];
    const date = (block.match(/(?<!ISO\s*:\s*["'][^"']*) \bdate:\s*["']([^"']+)["']/) || [])[1];

    // Resolve to ISO YYYY-MM-DD
    let lastmod = dateISO;
    if (!lastmod && date) {
      const parsed = new Date(date);
      if (!Number.isNaN(parsed.getTime())) {
        lastmod = parsed.toISOString().slice(0, 10);
      }
    }
    if (!lastmod) lastmod = new Date().toISOString().slice(0, 10);

    entries.push({ slug, lastmod });
  }

  // Deduplicate by slug (keep newest lastmod)
  const map = new Map();
  for (const e of entries) {
    const prev = map.get(e.slug);
    if (!prev || e.lastmod > prev.lastmod) map.set(e.slug, e);
  }
  return [...map.values()].sort((a, b) => (a.lastmod < b.lastmod ? 1 : -1));
}

export async function getBlogSlugs() {
  const posts = await getBlogPosts();
  return posts.map((p) => p.slug);
}

// ---------------------------------------------------------------------------
// Build sitemap XML
// ---------------------------------------------------------------------------
function buildSitemap(posts) {
  const today = new Date().toISOString().slice(0, 10);
  const currentYear = new Date().getFullYear();

  const urlNodes = posts.map((p) => {
    const yr = parseInt(p.lastmod.slice(0, 4), 10);
    const priority = currentYear - yr <= 1 ? '0.9' : '0.8';
    return `  <url>
    <loc>${SITE_URL}/blog/${p.slug}</loc>
    <lastmod>${p.lastmod}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${priority}</priority>
  </url>`;
  });

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Auto-generated by scripts/generate-blog-sitemap.mjs
  Source of truth: src/data/blogData.ts
  Do not edit by hand — changes will be overwritten on next build.
  Generated: ${today}
  Total posts: ${posts.length}
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
  <url>
    <loc>${SITE_URL}/blog</loc>
    <lastmod>${today}</lastmod>
    <changefreq>daily</changefreq>
    <priority>0.8</priority>
  </url>
${urlNodes.join('\n')}
</urlset>
`;
}

// ---------------------------------------------------------------------------
// CLI entrypoint
// ---------------------------------------------------------------------------
async function main() {
  const posts = await getBlogPosts();
  if (!posts.length) {
    console.error('✗ No blog posts found in src/data/blogData.ts');
    process.exit(1);
  }
  const xml = buildSitemap(posts);
  await writeFile(OUT_FILE, xml, 'utf8');
  console.log(`✓ Wrote ${path.relative(ROOT, OUT_FILE)} with ${posts.length} posts`);
  console.log(`  Newest: ${posts[0].slug} (${posts[0].lastmod})`);
  console.log(`  Oldest: ${posts[posts.length - 1].slug} (${posts[posts.length - 1].lastmod})`);
}

// Run when invoked directly (not when imported by prerender.mjs)
const invokedDirectly = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (invokedDirectly) {
  main().catch((err) => {
    console.error(err);
    process.exit(1);
  });
}
